"""Storage dispatch seam for the existing Engine's query and async job body.

Engine owns admission, locks, job lifecycle, cancellation and idempotency. This
adapter neither creates an Engine/profile nor starts a thread/listener. Root
registration is checked again when a persisted plan is applied. Repair generation
is an injected trusted local callable, never code supplied in a command argument.
"""
from __future__ import annotations

import base64
import json
from pathlib import Path

from ..application import DomainError
from ..core import differential_sync as sync, library_health as health
from ..core.restore_card import RestoreError
from . import inline_storage_actions
from ..core.inline_card import library as inline_library


class StorageActions:
    QUERY_NAMES = frozenset({"storage.health", "storage.transactions", "storage.plan"})
    SUBMIT_NAMES = frozenset({"storage.sync.plan", "storage.repair.plan", "storage.sync.apply", "storage.recover"}) | inline_storage_actions.NAMES

    def __init__(self, engine, *, repair_generator=None):
        self.engine = engine
        self.repair_generator = repair_generator

    def _card(self, value):
        return self.engine._under(value, self.engine.export_roots)

    def _sources(self, values):
        if not isinstance(values, dict):
            raise DomainError("INVALID_ARGUMENT", "source_roots must map selected source IDs to paths or null", {})
        return {identity: None if value is None else str(self.engine._under(value, self.engine.music_roots + self.engine.import_roots))
                for identity, value in values.items()}

    @staticmethod
    def _updates(values):
        if not isinstance(values, list):
            raise DomainError("INVALID_ARGUMENT", "updates must be a list of managed file units", {})
        result = []
        for value in values:
            item = dict(value)
            if "data_b64" in item:
                if "data" in item:
                    raise DomainError("INVALID_ARGUMENT", "Supply one generated byte representation", {})
                try:
                    item["data"] = base64.b64decode(item.pop("data_b64"), validate=True)
                except (ValueError, TypeError) as exc:
                    raise DomainError("INVALID_ARGUMENT", "Invalid generated base64 bytes", {}) from exc
            result.append(item)
        return result

    @staticmethod
    def _translate(function, *args, **kwargs):
        try:
            return function(*args, **kwargs)
        except RestoreError as exc:
            raise DomainError(exc.code.upper(), str(exc), exc.details) from exc

    def _load_plan(self, args):
        plan_id = args.get("plan_id", args.get("id"))
        with self.engine.connect() as connection:
            row = connection.execute("SELECT digest,body FROM plans WHERE id=?", (plan_id,)).fetchone()
        if row is None:
            raise DomainError("NOT_FOUND", "Storage plan not found", {})
        plan = json.loads(row[1])
        if plan.get("schema") != sync.PLAN_SCHEMA or sync._fingerprint(plan) != row[0]:
            raise DomainError("PLAN_STALE", "Stored record is not an intact storage plan", {})
        if "digest" in args and args["digest"] != row[0]:
            raise DomainError("PLAN_STALE", "Storage plan digest does not match", {})
        self._card(plan["root"])
        self._sources({identity: value["path"] for identity, value in plan["sources"].items()})
        return plan

    def query(self, name, args):
        if name == "storage.plan":
            record = self.engine.query("plans.get", {"id": args.get("plan_id", args.get("id"))})
            if "inline_plan" in record["plan"]:
                if args.get("digest", record["digest"]) != record["digest"]:
                    raise DomainError("PLAN_STALE", "Storage plan digest changed", {})
                return {"plan_id": record["id"], "digest": record["digest"], "plan": record["plan"]["inline_plan"]}
        if name in ("storage.health", "storage.transactions") and self._inline(args.get("root")):
            if name == "storage.transactions":
                from ..core.inline_card import delta
                root = delta.top(self._card(args["root"]))
                return {"transactions": delta.transactions(root), "retained_previous_trees": [str(path) for path in root.glob(".xm5-before-*") if path.is_dir()]}
            root, manifest = inline_library.load(self._card(args["root"]))
            sources = self._sources(args.get("source_roots", {}))
            result = inline_library.verify(root)
            result.update(schema="xm5.inline.health", source_roots=sources,
                          retained_modified=manifest.get("retained_modified", []),
                          source_status={key: "offline" if value is None or not Path(value).is_dir() else "available"
                                         for key, value in sources.items()},
                          rename_tracking=False, repair="Explicit source-backed preview; no automatic deletion")
            return result
        if name == "storage.health":
            root = self._card(args["root"])
            sources = self._sources(args.get("source_roots", {}))
            return self._translate(health.inspect_library, root, sources,
                                   find_relinks=bool(args.get("find_relinks", False)),
                                   expected_recipes=args.get("expected_recipes"))
        if name == "storage.transactions":
            return {"transactions": self._translate(sync.list_transactions, self._card(args["root"]))}
        if name == "storage.plan":
            plan = self._load_plan(args)
            return {"plan_id": plan["transaction_id"], "digest": plan["plan_sha256"], "plan": plan}
        raise DomainError("UNKNOWN_QUERY", "Unknown storage query", {})

    def submit(self, name, args, progress=None, cancel=None):
        """Execute one existing Engine job body; this does not enqueue another job."""
        if cancel is not None and cancel.is_set():
            raise InterruptedError("Storage job cancelled before execution")
        if name in inline_storage_actions.NAMES:
            return inline_storage_actions.submit(self.engine, name, args, progress, cancel)
        if name == "storage.recover" and self._inline(args.get("root")):
            from ..core.inline_card import delta
            root = self._card(args["root"])
            return delta.recover(root, args.get("transaction_id"), action=args.get("action", "rollback"),
                                 cancel=cancel, progress=progress)
        if name == "storage.sync.apply":
            record = self.engine.query("plans.get", {"id": args["plan_id"]})
            if "inline_plan" in record["plan"]:
                from .inline_library_actions import InlineLibraryActions
                return InlineLibraryActions(self.engine).dispatch("cards.execute", args, progress, cancel)
        if name in ("storage.sync.plan", "storage.repair.plan") and self._inline(args.get("root")):
            return self._inline_plan(args, progress, cancel)
        if name in {"storage.sync.plan", "storage.repair.plan"}:
            root = self._card(args["root"])
            sources = self._sources(args.get("source_roots", {}))
            if progress:
                progress({"phase": "storage_plan", "root": str(root)})
            if name == "storage.sync.plan":
                plan = self._translate(sync.plan_sync, root, sources, updates=self._updates(args.get("updates", [])),
                                       choices=args.get("choices"), manifest_metadata=args.get("manifest_metadata"))
            else:
                if self.repair_generator is None:
                    raise DomainError("UNSUPPORTED_CAPABILITY", "No retained-input local repair generator is configured", {})
                planner = getattr(self.repair_generator, "plan_repair", None)
                if callable(planner):
                    plan = self._translate(planner, root, sources, choices=args.get("choices"),
                                           expected_recipes=args.get("expected_recipes"))
                else:
                    plan = self._translate(health.plan_repair, root, sources, generator=self.repair_generator,
                                           choices=args.get("choices"), expected_recipes=args.get("expected_recipes"))
                self._translate(sync._validate_plan, plan)
                if plan["root"] != str(root):
                    raise DomainError("PATH_NOT_ALLOWED", "Repair planner returned a different library root", {})
                self._sources({identity: record["path"] for identity, record in plan["sources"].items()})
            if cancel is not None and cancel.is_set():
                raise InterruptedError("Storage job cancelled after planning")
            with self.engine.connect() as connection:
                connection.execute("INSERT INTO plans(id,digest,body) VALUES(?,?,?)",
                                   (plan["transaction_id"], plan["plan_sha256"], json.dumps(plan, ensure_ascii=False)))
            return {"plan_id": plan["transaction_id"], "digest": plan["plan_sha256"], "plan": plan}
        if name == "storage.sync.apply":
            if not isinstance(args.get("digest"), str):
                raise DomainError("INVALID_ARGUMENT", "Applying a storage plan requires its reviewed digest", {})
            return self._translate(sync.apply_plan, self._load_plan(args), progress=progress, cancel=cancel)
        if name == "storage.recover":
            root = self._card(args["root"])
            # Validate recovery sources against today's registered roots before
            # resume. Rollback needs only owned card backups and no source drive.
            journal = self._translate(sync._load_journal, root, args["transaction_id"])
            if args.get("action", "rollback") == "resume":
                self._sources({identity: value["path"] for identity, value in journal["plan"]["sources"].items()})
            return self._translate(sync.recover, root, args["transaction_id"], action=args.get("action", "rollback"),
                                   progress=progress, cancel=cancel)
        raise DomainError("UNKNOWN_COMMAND", "Unknown storage job command", {})

    def _inline(self, value):
        if not isinstance(value, str):
            return False
        root = self._card(value)
        if (root / inline_library.MANIFEST).is_file() or (root / "Struct/library.json").is_file():
            return True
        from ..core.inline_card import delta
        pointer = delta.top(root) / delta.POINTER
        if pointer.is_file():
            try:
                return json.loads(pointer.read_text(encoding="utf-8")).get("schema") == delta.SCHEMA
            except (OSError, ValueError):
                return False
        marker = delta.top(root) / delta.MARKER
        if marker.is_file():
            try:
                return json.loads(marker.read_text(encoding="utf-8")).get("schema") == "xm5.inline.incomplete"
            except (OSError, ValueError):
                return False
        return False

    def _inline_plan(self, args, progress, cancel):
        from .inline_library_actions import InlineLibraryActions
        from .engine import digest
        root, manifest = inline_library.load(self._card(args["root"]))
        sources = self._sources(args.get("source_roots", {}))
        available = [path for path in sources.values() if path is not None and Path(path).is_dir()]
        if not available:
            raise DomainError("SOURCE_OFFLINE", "Select an available registered source before sync or repair", {})
        if args.get("updates") or args.get("manifest_metadata"):
            raise DomainError("INVALID_ARGUMENT", "Inline libraries use library/playlist/tag commands before export; arbitrary generated-byte updates are not accepted", {})
        choices = args.get("choices") or {}
        if not isinstance(choices, dict) or any(value != "replace_from_source" for value in choices.values()):
            raise DomainError("INVALID_ARGUMENT", "Inline choices map exact owned card paths to replace_from_source", {})
        for path in choices:
            if path not in manifest["owned"] or not path.startswith(("xm5/music/", "xm5/EQ/")):
                raise DomainError("PATH_NOT_ALLOWED", "Only an explicitly owned source copy can be repaired", {"path": path})
        existing = {row["id"] for row in self.engine.application.query("playlists.list", {})["playlists"]}
        playlists = [row["id"] for row in manifest["playlists"] if row["id"] in existing]
        options = manifest.get("options", {})
        result = InlineLibraryActions(self.engine).dispatch("cards.plan", {
            "format": "XM5I", "roots": available, "destination": str(root / "xm5"), "existing": "update",
            "playlist_ids": playlists, "midpoint_dbfs": options.get("gain_midpoint_mdb", 0) / 1000,
            "correction_limit_db": options.get("gain_limit_mdb", 4000) / 1000}, progress, cancel)
        with self.engine.connect() as db:
            body = json.loads(db.execute("SELECT body FROM plans WHERE id=?", (result["plan_id"],)).fetchone()[0])
            body["inline_plan"]["replace_owned"] = sorted(choices)
            from ..core.inline_card import delta
            delta.annotate(body["inline_plan"])
            hashed = digest(body)
            db.execute("UPDATE plans SET digest=?,body=? WHERE id=?", (hashed, json.dumps(body), result["plan_id"]))
        result.update(digest=hashed, plan=body["inline_plan"])
        return result

    command = submit
