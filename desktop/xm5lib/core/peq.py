"""PEQ presets for the XM5 PEQ firmware (src/audio/vendor/peq.c is authoritative).

The manager edits a strict subset of what the firmware parser accepts:

* one common preamp (-60..24 dB),
* PK (peaking, Q required), LSC and HSC (centre-frequency shelves with explicit Q),
* each band scoped to both channels, L or R (firmware ``Channel:`` command),
* at most 30 enabled bands, Fc 20..20000 Hz, gain -24..24 dB, Q 0.1..10.

Anything else (LS/HS corner shelves, slope-only shelves, per-channel preamp, other APO commands) is
rejected with a reason; nothing is approximated. Response curves use the same RBJ formulas as the
firmware's ``peq_compile``.
"""
from __future__ import annotations

import cmath
import math
import re
from dataclasses import asdict, dataclass, field

TYPES = ("PK", "LSC", "HSC")
CHANNELS = ("ALL", "L", "R")
MAX_BANDS = 30
FILE_SOFT_LIMIT = 15 * 1024   # leave room for the header the player inserts (16384-byte hard limit)
LINE_LIMIT = 512
LIMITS = {"fc": (20.0, 20000.0), "gain": (-24.0, 24.0), "q": (0.1, 10.0), "preamp": (-60.0, 24.0)}


@dataclass
class Band:
    type: str = "PK"
    fc: float = 1000.0
    gain: float = 0.0
    q: float = 1.0
    enabled: bool = True
    channel: str = "ALL"


@dataclass
class Preset:
    name: str
    preamp: float = 0.0
    bands: list[Band] = field(default_factory=list)
    notes: str = ""
    source: str = ""          # provenance, e.g. "peace:C:/.../HD600 Harman.peace"
    source_sha256: str = ""

    def to_dict(self) -> dict:
        return asdict(self)

    @classmethod
    def from_dict(cls, d: dict) -> "Preset":
        return cls(name=d["name"], preamp=float(d.get("preamp", 0)), notes=d.get("notes", ""),
                   source=d.get("source", ""), source_sha256=d.get("source_sha256", ""),
                   bands=[Band(**b) for b in d.get("bands", [])])

    def active(self) -> list[Band]:
        return [b for b in self.bands if b.enabled]


# ------------------------------------------------------------------ validation

_FILENAME_BAD = re.compile(r'[\x00-\x1f<>:"/\\|?*]')


def safe_filename(name: str) -> str:
    """ASCII filename for EQ/<name>.txt (firmware: <= 63 bytes incl. extension, no leading dot)."""
    s = name.encode("ascii", "ignore").decode()
    s = _FILENAME_BAD.sub("-", s).strip().replace(" ", "-")
    s = re.sub(r"-{2,}", "-", s).strip("-.") or "Preset"
    s = s.replace("..", ".")
    return s[:59] + ".txt"


def validate(p: Preset) -> list[str]:
    errors = []
    lo, hi = LIMITS["preamp"]
    if not _finite(p.preamp) or not lo <= p.preamp <= hi:
        errors.append(f"Preamp {p.preamp} dB outside {lo:g}..{hi:g} dB")
    if not p.name.strip():
        errors.append("Preset name is empty")
    if len(p.active()) > MAX_BANDS:
        errors.append(f"{len(p.active())} enabled bands; the firmware accepts at most {MAX_BANDS}")
    for i, b in enumerate(p.bands, 1):
        if b.type not in TYPES:
            errors.append(f"Band {i}: type {b.type} not supported")
        if b.channel not in CHANNELS:
            errors.append(f"Band {i}: channel {b.channel} not supported")
        for key in ("fc", "gain", "q"):
            v = getattr(b, key)
            lo, hi = LIMITS[key]
            if not _finite(v) or not lo <= v <= hi:
                errors.append(f"Band {i}: {key} {v} outside {lo:g}..{hi:g}")
    return errors


def _finite(v) -> bool:
    return isinstance(v, (int, float)) and math.isfinite(v)


# ------------------------------------------------------------------ number formatting

def _thousands_ambiguous(tok: str) -> bool:
    # peq.c thousands_ambiguous(): >=5 chars, no exponent, '.' four from the end.
    return "e" not in tok.lower() and len(tok) >= 5 and tok[-4] in ".,"


def fmt(v: float, frequency: bool = False) -> str:
    """Shortest round-trip decimal; scientific form when a frequency would look like 1.234 kHz."""
    v = float(v)
    if v == 0:
        return "0"
    s = repr(v)
    if s.endswith(".0"):
        s = s[:-2]
    if "e" in s:  # repr chose scientific (e.g. 1e-05): already unambiguous and accepted
        return s
    if frequency and _thousands_ambiguous(s):
        for digits in range(1, 18):
            cand = f"{v:.{digits}e}"
            if float(cand) == v:
                mant, exp = cand.split("e")
                mant = mant.rstrip("0").rstrip(".")
                return f"{mant}e{int(exp)}"
    return s


# ------------------------------------------------------------------ APO text

def to_apo_text(p: Preset) -> str:
    errors = validate(p)
    if errors:
        raise ValueError("; ".join(errors))
    lines = [f"# XM5 PEQ preset: {p.name.encode('ascii', 'replace').decode()}",
             "# Generated by XM5 Library. Common stereo unless a Channel line says otherwise.",
             f"Preamp: {fmt(p.preamp)} dB"]
    scope = "ALL"
    for n, b in enumerate(p.bands, 1):
        if b.channel != scope:
            lines.append(f"Channel: {'all' if b.channel == 'ALL' else b.channel}")
            scope = b.channel
        state = "ON" if b.enabled else "OFF"
        lines.append(f"Filter {n}: {state} {b.type} Fc {fmt(b.fc, True)} Hz Gain {fmt(b.gain)} dB Q {fmt(b.q)}")
    if scope != "ALL":
        lines.append("Channel: all")
    text = "\n".join(lines) + "\n"
    if len(text.encode()) > FILE_SOFT_LIMIT:
        raise ValueError(f"preset text is {len(text.encode())} bytes; keep it under {FILE_SOFT_LIMIT}")
    return text


class ParseError(ValueError):
    def __init__(self, line: int, reason: str):
        super().__init__(f"line {line}: {reason}")
        self.line, self.reason = line, reason


_NUM = re.compile(r"[+-]?(?:\d+(?:[.,]\d*)?|[.,]\d+)(?:[eE][+-]?\d+)?$")
_UNSUPPORTED = {"device", "if", "elseif", "else", "endif", "eval", "include", "stage", "iir", "biquad", "delay",
                "copy", "convolution", "graphiceq", "vstplugin", "loudnesscorrection"}


def _number(tok: str) -> float:
    if not tok or len(tok) >= 64 or not _NUM.match(tok):
        raise ValueError(tok)
    v = float(tok.replace(",", "."))
    if not math.isfinite(v):
        raise ValueError(tok)
    return v


def parse_apo_text(text: str, name: str) -> tuple[Preset, list[str]]:
    """Parse APO text into the manager's subset. Returns (preset, notes); raises ParseError.

    Mirrors the firmware's grammar for the commands it accepts; additionally rejects firmware-legal
    forms the editor cannot represent exactly (LS/HS corner shelves, slope-only shelves, per-channel
    preamp) instead of converting them.
    """
    if "\x00" in text:
        raise ParseError(1, "embedded NUL (UTF-16 is not supported)")
    if len(text.encode("utf-8")) > 16384:
        raise ParseError(1, "file exceeds 16384 bytes")
    text = text.lstrip("\ufeff")
    preset = Preset(name=name)
    notes: list[str] = []
    scope = "ALL"
    for ln, raw in enumerate(text.split("\n"), 1):
        line = raw[:-1] if raw.endswith("\r") else raw
        if "\r" in line:
            raise ParseError(ln, "CR without LF")
        if len(line.encode()) > LINE_LIMIT:
            raise ParseError(ln, "line exceeds 512 bytes")
        s = line.strip(" \t")
        if not s or s.startswith("#"):
            continue
        if "`" in s:
            raise ParseError(ln, "inline expressions are not supported")
        if ":" not in s:
            notes.append(f"line {ln}: ignored (no ':'): {s[:40]}")
            continue
        key, rest = s.split(":", 1)
        key = key.rstrip(" \t")
        words = rest.split()
        if key == "Preamp":
            if scope != "ALL":
                raise ParseError(ln, "per-channel preamp is not editable here (firmware maps it to balance)")
            tok = words[0] if words else ""
            if len(words) == 1 and tok.lower().endswith("db"):
                tok, unit = tok[:-2], "db"
            else:
                unit = words[1].lower() if len(words) > 1 else ""
                if len(words) > 2 and not words[2].startswith("#"):
                    raise ParseError(ln, "expected Preamp: <gain> dB")
            try:
                g = _number(tok)
            except ValueError:
                raise ParseError(ln, "expected Preamp: <gain> dB") from None
            if unit != "db":
                raise ParseError(ln, "expected Preamp: <gain> dB")
            if not -60 <= g <= 24:
                raise ParseError(ln, "preamp outside -60..24 dB")
            preset.preamp += g
            continue
        if key == "Channel":
            names = [w.lower() for w in rest.split(" ") if w]
            if not names or any(n not in ("l", "r", "all") for n in names):
                raise ParseError(ln, "only channels L, R and all are supported")
            l = any(n in ("l", "all") for n in names)
            r = any(n in ("r", "all") for n in names)
            scope = "ALL" if l and r else "L" if l else "R"
            continue
        if re.fullmatch(r"Filter[ \t]*\d*", key):
            if not words:
                raise ParseError(ln, "expected ON or OFF")
            if words[0].lower() == "off":
                band = _filter_words(words[1:], ln, strict=False)
                if band is None:
                    notes.append(f"line {ln}: disabled filter not representable; omitted (inactive)")
                else:
                    band.enabled, band.channel = False, scope
                    preset.bands.append(band)
                continue
            if words[0] != "ON":
                raise ParseError(ln, "expected ON or OFF")
            if len(words) >= 2 and words[1] == "None":
                if len(words) > 2:
                    raise ParseError(ln, "unexpected text after None")
                continue
            band = _filter_words(words[1:], ln, strict=True)
            band.channel = scope
            preset.bands.append(band)
            continue
        if key.lower() in _UNSUPPORTED or key.lower() in ("preamp", "channel") or key.lower().startswith("filter"):
            raise ParseError(ln, f"unsupported command '{key}'")
        notes.append(f"line {ln}: '{key}:' is not an APO command; ignored as by the firmware")
    errors = validate(preset)
    if errors:
        raise ParseError(0, "; ".join(errors))
    return preset, notes


def _filter_words(w: list[str], ln: int, strict: bool) -> Band | None:
    def fail(reason):
        if strict:
            raise ParseError(ln, reason)
        return None
    if not w:
        return fail("missing filter type")
    kind = w[0]
    if kind == "PEQ":
        kind = "PK"
    if kind in ("LS", "HS"):
        return fail(f"{kind} with Q uses APO corner-frequency semantics; not editable here (LSC/HSC are)")
    if kind not in TYPES:
        return fail(f"unsupported filter type {kind}")
    # Fixed order: Fc <n> Hz Gain <n> dB Q <n>  (units may be attached: 100Hz, 3dB)
    toks = []
    for t in w[1:]:
        if t.startswith("#"):
            break
        m = re.fullmatch(r"([+\-0-9.,eE]+)(Hz|dB)", t)
        toks.extend([m.group(1), m.group(2)] if m else [t])
    if len(toks) < 6 or toks[0] != "Fc" or toks[2] != "Hz" or toks[3] != "Gain" or toks[5] != "dB":
        return fail("expected Fc <Hz> Hz Gain <dB> dB Q <q>")
    if _thousands_ambiguous(toks[1]):
        return fail("ambiguous Fc: three decimals read as a thousands separator")
    if len(toks) == 6:
        return fail("peaking filter requires Q" if kind == "PK" else "shelf without Q uses a slope default; not editable here")
    if len(toks) != 8 or toks[6] != "Q":
        return fail("unsupported filter form")
    try:
        fc, gain, q = _number(toks[1]), _number(toks[4]), _number(toks[7])
    except ValueError:
        return fail("invalid number")
    b = Band(kind, fc, gain, q)
    if not (20 <= fc <= 20000 and -24 <= gain <= 24 and 0.1 <= q <= 10):
        return fail("range: 20..20000 Hz, -24..24 dB, Q 0.1..10")
    return b


# ------------------------------------------------------------------ response (RBJ, as peq_compile)

def coefficients(b: Band, rate: int) -> tuple[float, float, float, float, float] | None:
    if not b.enabled or b.gain == 0:
        return None
    if not b.fc < rate * 0.5:
        raise ValueError(f"{b.fc:g} Hz is at or above Nyquist for {rate} Hz")
    a = 10 ** (b.gain / 40)
    w = 2 * math.pi * b.fc / rate
    c, alpha = math.cos(w), math.sin(w) / (2 * b.q)
    r = 2 * math.sqrt(a) * alpha
    if b.type == "PK":
        b0, b1, b2, a0, a1, a2 = 1 + alpha * a, -2 * c, 1 - alpha * a, 1 + alpha / a, -2 * c, 1 - alpha / a
    elif b.type == "LSC":
        b0 = a * ((a + 1) - (a - 1) * c + r); b1 = 2 * a * ((a - 1) - (a + 1) * c)
        b2 = a * ((a + 1) - (a - 1) * c - r); a0 = (a + 1) + (a - 1) * c + r
        a1 = -2 * ((a - 1) + (a + 1) * c); a2 = (a + 1) + (a - 1) * c - r
    else:
        b0 = a * ((a + 1) + (a - 1) * c + r); b1 = -2 * a * ((a - 1) + (a + 1) * c)
        b2 = a * ((a + 1) + (a - 1) * c - r); a0 = (a + 1) - (a - 1) * c + r
        a1 = 2 * ((a - 1) - (a + 1) * c); a2 = (a + 1) - (a - 1) * c - r
    return b0 / a0, b1 / a0, b2 / a0, a1 / a0, a2 / a0


def log_frequencies(n: int = 256, lo: float = 20, hi: float = 20000) -> list[float]:
    return [lo * (hi / lo) ** (i / (n - 1)) for i in range(n)]


def response(p: Preset, rate: int = 48000, freqs: list[float] | None = None) -> dict[str, list[float]]:
    """Magnitude in dB per channel ('L', 'R') including preamp."""
    freqs = freqs or log_frequencies()
    out = {}
    for ch in ("L", "R"):
        coeffs = [c for b in p.bands if b.channel in ("ALL", ch) and (c := coefficients(b, rate))]
        curve = []
        for f in freqs:
            z = cmath.exp(-1j * 2 * math.pi * min(f, rate / 2 * 0.9999) / rate)
            db = p.preamp
            for b0, b1, b2, a1, a2 in coeffs:
                h = (b0 + b1 * z + b2 * z * z) / (1 + a1 * z + a2 * z * z)
                db += 20 * math.log10(max(abs(h), 1e-12))
            curve.append(db)
        out[ch] = curve
    return out


def headroom(p: Preset, rate: int = 48000) -> tuple[float, float]:
    """(peak dB, frequency) of the sampled response; an estimate, not a clipping guarantee."""
    freqs = log_frequencies(512)
    best = (-1e9, 0.0)
    for curve in response(p, rate, freqs).values():
        for f, db in zip(freqs, curve):
            if db > best[0]:
                best = (db, f)
    return best
